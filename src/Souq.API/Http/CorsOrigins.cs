namespace Souq.API.Http;

// ============================================================================
// الأصول المسموح لها بمخاطبة الـ API عبر المتصفّح.
//
// الواجهة تطلب مسارات نسبية (/api) دائماً: وكيل Vite يمرّرها في التطوير، وnginx في النشر.
// فالنظام أحادي الأصل في كل بيئاته ولا يحتاج CORS أصلاً — والسياسة هنا للحالات الاستثنائية
// وحدها (واجهة تُشغَّل على أصل آخر أثناء تطوير أو تكامل).
//
// الاحتياطي على localhost:5173 كان يُطبَّق في كل بيئة بما فيها الإنتاج: أصل تطوير مسموح به
// بصمت على خادم حقيقي. لا يُستغَلّ عن بُعد بسهولة (السياسة لا تسمح بالاعتمادات)، لكنه تسرّب
// افتراضٍ تطويري إلى الإنتاج — وهو ما يمنعه بقية إعداد هذا التطبيق بانتظام.
// ============================================================================
public static class CorsOrigins
{
    public static readonly string[] LocalDevelopmentDefault = ["http://localhost:5173"];

    // إعداد صريح يغلب دائماً؛ وبلا إعداد: أصل التطوير محلياً، ولا شيء خارجه.
    public static string[] For(string[]? configured, bool localEnvironment) =>
        configured is { Length: > 0 } ? configured
        : localEnvironment ? LocalDevelopmentDefault
        : [];
}
