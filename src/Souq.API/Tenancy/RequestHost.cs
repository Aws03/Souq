using Microsoft.AspNetCore.Http;

namespace Souq.API.Tenancy;

// ============================================================================
// الصيغة القانونية لمضيف الطلب — **موضعٌ واحد يستعمله كل من يفتح مفتاحاً بالمضيف** (M15).
//
// **لماذا صنفٌ لسطرٍ واحد؟** لأنّ السطر كان مكتوباً في مكان ومنسيّاً في آخر، وكان ذلك ثغرةً حقيقية:
// تحديد المتجر كان يُطبّع المضيف (`.TrimEnd('.').ToLowerInvariant()`) بينما حدّ المعدّل يفتح دلوه
// بالمضيف **كما وصل**. فـ`Shop.example.com` و`shop.example.com` و`shop.example.com.` متجرٌ واحد وثلاثة
// دلاء — وبتبديل حالة الأحرف وحدها يصير لكل طلبٍ دلوُه، فينعدم الحدّ.
//
// وقد أُثبت عمليّاً قبل الإصلاح على حزمة حاويات تعمل: عشرة طلبات بمضيفٍ ثابت ثمّ 429، وأربعة عشر طلباً
// باختلاف حالة الأحرف وحدها — كلّها 401، ولا 429 واحدة. أي أنّ كل ما يحرسه الحدّ (حشو بيانات الاعتماد،
// إغراق بريد إعادة التعيين، تخمين الكوبونات، إنشاء الحسابات) كان مفتوحاً بلا حدّ.
//
// و`Request.Host.Host` يحفظ حالة الأحرف والنقطة الأخيرة كما أرسلها العميل، وnginx يمرّرها حرفياً
// (`proxy_set_header Host $http_host`) — فالتطبيع مسؤولية التطبيق وحده، ولا شيء قبله يقوم به.
//
// نفس قاعدة `TenantDomain.NormalizeHost` في المجال ("صيغة واحدة لكل مضيف في النظام")، مكرَّرةً هنا بلا
// تحقّقٍ من صلاحية تسميات DNS: هذا مسار كل طلب، ووظيفته توحيد المفتاح لا رفض المدخل. المضيف غير الصالح
// يُوحَّد أيضاً ثمّ لا يطابق متجراً فيُردّ 404 — وهو الصواب.
// ============================================================================
public static class RequestHost
{
    public static string Canonical(HttpContext context) => Canonical(context.Request.Host.Host);

    public static string Canonical(string? host) =>
        (host ?? string.Empty).TrimEnd('.').ToLowerInvariant();
}
