namespace Souq.API.Security;

// ============================================================================
// بادئة `__Host-` لملفّات تعريف الارتباط التي تُصادِق (M15).
//
// **ما تحرسه ليس ما يبدو.** `HttpOnly` يمنع قراءة الملفّ من السكربت، و`Secure` يمنع إرساله بلا تشفير،
// و`SameSite=Strict` يمنع المتصفّح من إرساله مع طلبٍ **من موقعٍ آخر**. ولا شيء في الثلاثة يمنع مضيفاً
// شقيقاً من **كتابة** ملفٍّ يُرسَل معنا: `SameSite` مداره النطاق المُسجَّل لا الأصل، وملفّات تعريف الارتباط
// لا تخضع لسياسة الأصل الواحد أصلاً.
//
// **وسوق منصّةٌ بعلامةٍ بيضاء: التجّار يأتون بنطاقاتهم** (`TenantDomains`). فما يعيش تحت نطاق التاجر غير
// متجره ليس تحت سيطرة المنصّة — نطاقٌ فرعي تسويقي، أو صفحة حالة، أو CNAME قديم لم يُنظَّف. ومن يملك
// أيّاً منها يكتب:
//
//     Set-Cookie: souq_refresh=<رمز المهاجم نفسه>; Domain=.acme.com; Path=/api/auth; Secure
//
// وهو ملفٌّ من نفس الموقع، فـ`SameSite=Strict` يُرسله؛ وليس مقصوراً على مضيفٍ واحد، فيجلس إلى جانب ملفّ
// الضحيّة أو أمامه. ثمّ تنادي واجهة المتجر `POST /api/auth/refresh` عند كل فتح صفحة، فتعود بجلسة
// **حساب المهاجم** — ويتسوّق الضحيّة ويحفظ عنوانه ويُتمّ شراءه داخل حساب المهاجم، حيث يقرأ ذلك كلّه.
//
// **و`__Host-` هي ما يُغلق هذا بالضبط**، لا `__Secure-`: المتصفّح يرفض أي ملفٍّ بهذه البادئة يحمل
// `Domain`، فيصير مقصوراً على مضيفٍ واحد بالقوّة — والشقيق الذي يكتبه يكتبه **لنفسه** ولا يصلنا منه شيء.
// (`__Secure-` تشترط التشفير وحده، ولا تمنع `Domain`، فلا تمنع هذا الهجوم.)
//
// **والثمن مدفوعٌ بعلم**: البادئة تشترط `Path=/`، فيُرسَل الملفّ مع كل طلبٍ إلى الأصل نفسه بدل مسار
// المصادقة وحده. وهو تراجعٌ صغير — ملفٌّ `HttpOnly` مشفَّر إلى الخادم ذاته — مقابل إغلاق استيلاءٍ كامل
// على الحساب. أمّا المسار الضيّق فيبقى حيث لا بادئة (انظر أدناه).
//
// **والبادئة تُعلَّق حين لا يكون الملفّ مشفَّراً**: المتصفّح يرفض `__Host-` بلا `Secure` **رفضاً تامّاً** —
// لا يُخزَّن أصلاً. فلو فُرضت دائماً لانكسر الدخول في التطوير وفي حزمة الحاويات المحلّية (كلاهما http)
// انكساراً صامتاً يبدو كأنّ الجلسة لا تُحفظ. فحين `Secure` مُطفأ يبقى الاسم والمسار القديمين: بيئةٌ بلا
// تشفير ليست البيئة التي يُدافَع فيها عن نطاقٍ حقيقي أصلاً.
// ============================================================================
public static class HostOnlyCookie
{
    public const string Prefix = "__Host-";

    /// الاسم كما يُكتب ويُقرأ: بالبادئة حين يكون الملفّ مشفَّراً، وبالاسم العاري حين لا يكون.
    public static string NameFor(string bareName, bool secure) => secure ? Prefix + bareName : bareName;

    /// `/` مع البادئة (شرطها)، والمسار الضيّق حين لا بادئة.
    public static string PathFor(string narrowPath, bool secure) => secure ? "/" : narrowPath;
}
