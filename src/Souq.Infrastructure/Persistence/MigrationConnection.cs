// سلسلة اتصال الهجرات — منفصلة عن سلسلة التشغيل عمداً (R-12).
//
// الهجرات تحتاج صلاحيات تغيير المخطّط (إنشاء جداول، فهارس، مفاتيح أجنبية، ونقل بيانات).
// التشغيل العادي لا يحتاج شيئاً من ذلك: قراءة وكتابة صفوف فقط. وما دامت الهجرات تُطبَّق
// عند الإقلاع (R-18)، فالاتصالان يعيشان في العملية نفسها — لكن ليس بالضرورة بالهوية نفسها،
// وهذا هو الفرق بين "التطبيق يملك قاعدته" و"التطبيق يقرأ ويكتب فيها".
//
// بلا ConnectionStrings:Migrations يعود كل شيء إلى Default تماماً كما كان: أي نشر قائم
// لا يتغيّر سلوكه بإضافة هذا الملف، والفصل قرار نشر يُتَّخذ متى جهز.
// ============================================================================
public sealed record MigrationConnection(string Value, bool IsSeparateIdentity);
