namespace Souq.Domain.Enums;

// حالة حجز مخزون (المرحلة 6). Active وحدها تحجز من المتاح؛ كل انتقال منها نهائي ويحدث مرّة واحدة.
public enum ReservationStatus
{
    Active = 0,     // يحجز من المتاح لطلب لم يُدفع بعد
    Committed = 1,  // دُفع الطلب: خرجت الكمية من الموجود (حركة بيع)
    Released = 2,   // أُلغي الطلب قبل الدفع أو فشل دفعه: عادت الكمية للمتاح
    Expired = 3,    // انتهت مهلة الدفع فأُلغي الطلب: عادت الكمية للمتاح
    Restocked = 4,  // أُلغي طلب مدفوع قبل شحنه: عادت الكمية للموجود (حركة إلغاء)
}
