namespace Souq.Domain.Enums;

// سبب تغيّر المخزون. نوع الحركة يفسّر السبب، والكمية (QuantityChange) تحمل
// الاتجاه بإشارتها (سالب = نقص، موجب = زيادة). فصل السبب عن المقدار يجعل سجلّ
// المخزون قابلاً للقراءة والتدقيق دون تخمين.
public enum StockMovementType
{
    Purchase = 0,    // توريد/شراء — زيادة المخزون (يشمل المخزون الابتدائي عند الإنشاء)
    Sale = 1,        // بيع — نقص المخزون عند إتمام طلب
    Adjustment = 2,  // تصحيح يدوي من الإدارة — قد يزيد أو ينقص
    Return = 3,      // إرجاع من العميل — زيادة المخزون
    Cancellation = 4, // إلغاء طلب لم يُشحن (أو فشل دفعه) — يعكس حركة Sale ويُعيد المحجوز
}
