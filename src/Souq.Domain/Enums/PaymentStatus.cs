namespace Souq.Domain.Enums;

// حالة دفعة طلب لدى البوّابة (المرحلة 11). الاسترداد لا يغيّرها: دفعة ناجحة استُردّ بعضها أو كلها تبقى Succeeded،
// ومبلغ المسترَدّ يُقرأ منها — فالتقارير تفرّق "دُفع ثم رُدّ" عن "لم يُدفع".
public enum PaymentStatus
{
    Pending = 0,    // نيّة دفع أُنشئت ولم تُحسم
    Succeeded = 1,  // البوّابة أكّدت الدفع
    Failed = 2,     // البوّابة رفضت أو فشل الدفع
    Cancelled = 3,  // أُلغي الطلب قبل الدفع (العميل، انتهاء المهلة، فشل بدء الدفع)
}
