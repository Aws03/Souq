namespace Souq.Domain.Interfaces;

// ============================================================================
// IUnitOfWork — "وحدة العمل". لماذا؟
// عند إنشاء طلب نقوم بعدة تغييرات: ننقص مخزون المنتجات + نضيف الطلب.
// يجب أن تنجح كلها معاً أو تفشل كلها معاً (Transaction). إن نجح إنقاص المخزون
// ثم فشل حفظ الطلب، نكون قد خسرنا مخزوناً دون بيع — كارثة بيانات.
// وحدة العمل تضمن الحفظ الذرّي: SaveChanges واحدة تحفظ كل شيء أو لا شيء.
// ============================================================================
public interface IUnitOfWork
{
    Task<int> SaveChangesAsync(CancellationToken ct = default);
}
