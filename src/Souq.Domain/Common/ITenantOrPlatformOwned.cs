namespace Souq.Domain.Common;

// ============================================================================
// صف يخصّ متجراً أو المنصّة نفسها (TenantId = null): حسابات الدخول وجلساتها (ADR-0010، D-06).
//   في نطاق متجر   ⇒ المرشّح يُظهر صفوف ذلك المتجر فقط، وحارس الكتابة يختم TenantId.
//   في نطاق المنصّة ⇒ المرشّح يُظهر صفوف المنصّة فقط (TenantId IS NULL)، والإضافة تبقى بلا متجر.
//   بلا نطاق       ⇒ أي قراءة أو كتابة ترمي.
// BelongsToPlatform يقرّر أين يجوز إنشاء الصف: حساب منصّة لا يُنشأ داخل متجر، ولا حساب متجر في
// نطاق المنصّة (عمليات المنصّة على متجر تعمل في نطاق ذلك المتجر — TenantScopes).
// ============================================================================
public interface ITenantOrPlatformOwned
{
    int? TenantId { get; }

    bool BelongsToPlatform { get; }
}
