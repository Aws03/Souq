namespace Souq.Domain.Common;

// ============================================================================
// ITenantOwned — علامة "هذا الصف يخصّ متجراً واحداً" (MultiTenancy.md §4, ADR-0005).
// كل كيان يحملها يحصل تلقائياً في Infrastructure على: مرشّح استعلام عام (WHERE TenantId = @current)،
// ختم TenantId عند الإضافة، ورفض أي تعديل/حذف لصف مستأجر آخر، ومفتاح أجنبي إلى Tenants.
// لا setter هنا ولا في الكيانات: المستأجر يختمه حارس الكتابة من سياق الطلب — لا يأتي من
// العميل ولا من المعالج، ولا يتغيّر بعد الإنشاء أبداً.
// ============================================================================
public interface ITenantOwned
{
    int TenantId { get; }
}
