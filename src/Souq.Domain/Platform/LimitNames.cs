using Souq.Domain.Exceptions;

namespace Souq.Domain.Platform;

// ============================================================================
// أسماء الحدود القابلة للعدّ (C2، ADR-0049 وADR-0054) — كتالوج مغلق، ومقابله في الاستحقاقات
// هو Entitlements.All.
//
// **C1 ترك العضوية بلا تحقّق عمداً، وC2 يعكس ذلك عمداً** — والسبب مختلف عمّا مُنع من أجله هناك:
// C1 امتنع كي لا يجيب قرار المالك C-12 (ما الشرائح وما حدودها) ضمناً. وهذا الكتالوج **لا يجيبه**:
// لا قيمة هنا ولا سعر ولا شريحة — هو قائمة ما **تعرف الآلة أن تعدّه** لا قائمة ما يُباع. القيم
// تبقى في الخطة، وهي وحدها سؤال المالك.
//
// ولماذا صار الرفض لازماً أصلاً؟ لأن الفرض وُجد. حدٌّ باسم لا عدّاد خلفه هو **وعد لا يُنفَّذ**:
// يُكتب في العقد، ويُعرض على الشاشة، ولا يمنع شيئاً أبداً — بلا خطأ ولا سجلّ. وهو بعينه ما ترفضه
// Plan.SetEntitlements لمفتاح استحقاق مجهول بالحجّة نفسها: "الخطة عقد، وتجاهل ما فيها بصمت يعني
// بيع قدرة لا تُمنح". النظير هنا: بيع **قيدٍ لا يقيّد** — أو أسوأ، سقفٌ يعتمد عليه التاجر وليس له
// وجود.
//
// إضافة اسم هنا ليست قراراً تجارياً بل تعهّد هندسي من ثلاثة أطراف لا يجوز أن يُنفَّذ واحدٌ منها
// دونها (ADR-0054 §القرار): قاعدة عدّ في QuotaResources، وحجزٌ على مسار الإنشاء، وإطلاقٌ على مسار
// الحذف. الاختبار المعماري يُلزم بالأولى؛ والثنتان الباقيتان مراجعةٌ بشرية يسمّيها دليل التغيير.
// ============================================================================
public static class LimitNames
{
    // ============================================================================
    // **ما يُعَدّ هو ما يمكن للتاجر أن يُفرّغه.** القاعدة الحاكمة للاسمين أدناه، وهي ليست تفصيلاً:
    // لا حذف فعليّ لأيٍّ منهما في هذا المستودع — المنتج يُؤرشف (DeleteProductHandler يستدعي
    // Archive)، والموظّف يُعطَّل ولا مسار حذفٍ له أصلاً. فلو عُدَّ المؤرشَف والمعطَّل لصار الحدّ
    // **سقّاطة باتجاه واحد**: يمتلئ ولا يُفرَّغ أبداً، ولا يبقى أمام تاجر بلغ سقفه إلّا ترقية
    // الخطة — وهو ابتزازٌ بالتصميم لا تسعيرٌ، ولم يقرّره أحد.
    // ============================================================================

    // منتجات المتجر **غير المؤرشفة**. الأرشفة هي حذف هذا المستودع، فهي تُطلق الحصّة.
    public const string CatalogProducts = "catalog.products";

    // مقاعد الموظّفين: حسابات المتجر الإدارية **غير المعطّلة** — والدعوة المعلّقة تشغل مقعداً،
    // وإلّا استُهلك الحدّ كلّه بدعواتٍ لا يقبلها أحد.
    public const string StaffSeats = "staff.seats";

    public static IReadOnlyList<string> All => [CatalogProducts, StaffSeats];

    public static bool IsKnown(string? name) => name is not null && All.Contains(name);

    // الشكل أولاً (Limit.NormalizeName) ثم العضوية: رسالة "اسم غير معروف" لنصٍّ مشوّه تُضلّل.
    public static string Normalize(string? name)
    {
        var normalized = Limit.NormalizeName(name);
        if (!IsKnown(normalized))
            throw new InvalidPlanException(
                $"حدّ غير معروف: {name} — المعروف: {string.Join(", ", All)}");
        return normalized;
    }
}
