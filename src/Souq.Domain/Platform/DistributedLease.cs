using Souq.Domain.Common;
using Souq.Domain.Exceptions;

namespace Souq.Domain.Platform;

// ============================================================================
// عقدُ إيجارٍ مُسمّى تتنازعه نسخُ الخادم (C4، [ADR-0057](0057)): صفٌّ واحد لكل عملٍ لا يجوز أن
// يجري مرّتين في وقتٍ واحد. جدولُ منصّةٍ **عالميّ بلا متجر** (الشكل C في ADR-0047 §1) — لأنّ
// المتنازعين نسخُ خادمٍ لا متاجر، والعملُ الذي يحرسه قد يعبر المتاجر كلَّها.
//
// ============================================================================
// **ولماذا جدولٌ في SQL Server ولا شيء آخر؟**
//
// لأنّ القاعدةَ هي الحالةُ المشتركة **الوحيدة** التي يملكها هذا النظام. والمخزنُ الموزَّع
// (Redis) غيرُ مقصودٍ صراحةً ([ExplicitNonGoals §9](../../../docs/02-ARCHITECTURE/ExplicitNonGoals.md))،
// ووسيطُ الرسائل كذلك (§3) — فإدخالُ أيٍّ منهما لقفلٍ واحد يشتري تبعيةَ تشغيلٍ كاملة مقابل
// جدولٍ من أربعة أعمدة.
//
// و`sp_getapplock` كان سيؤدّي الغرض ويأتي بأقفالٍ حقيقية من المحرّك، لكنّه **SQL خام**، ويمنعه
// `لا_SQL_خام_في_Infrastructure_خارج_الهجرات` بحقّ: قفلٌ بجملةٍ نصّية لا يراه مرشّحُ المستأجر
// ولا يقرؤه أحد. فالنمطُ المُختار هو نمطُ صندوق الصادر بعينه — تحديثٌ مشروط يحجز مدّةً — وهو
// مُجرَّبٌ في هذا المستودع منذ المرحلة 14 وقد دُقّق في المرحلة 17.
// ============================================================================
//
// **والإيجارُ ينتهي، ولا يُفكّ بيد ميت.** نسخةٌ تسقط وهي حاملةٌ للعقد لا تُفرج عنه أبداً، فلو كان
// القفلُ أبديّاً لتوقّف ذلك العمل إلى أن يتدخّل إنسان. فالمدّةُ محدودة، وحاملُ العقد يُجدّدها ما
// دام يعمل، وانتهاؤها **هو** آلية التعافي لا حالةَ خطأ.
// ============================================================================
public class DistributedLease : Entity
{
    public const int NameMaxLength = 100;
    public const int OwnerMaxLength = 64;

    // اسمُ العمل المحروس. نصٌّ لا تعداد: الأعمالُ تُضاف في وحداتٍ مختلفة، وتعدادٌ مركزيّ كان
    // سيُجبر كلَّ وحدةٍ على تعديل ملفٍّ مشترك كي تحرس عملَها.
    public string Name { get; private set; } = default!;

    // مَن يحمله الآن: رمزُ نسخةٍ تُولّده عند إقلاعها. `null` ⇒ حرّ.
    public string? Owner { get; private set; }

    public DateTime? AcquiredAtUtc { get; private set; }

    // متى ينتهي. **الماضي يعني حرّاً** ولو بقي `Owner` مكتوباً — فالقراءة تنظر إلى الوقت لا إلى
    // وجود الاسم، وإبقاءُ اسمِ آخرِ حامل بعد انتهائه مقصود: هو أوّلُ ما يُسأل عنه حين يُحقَّق
    // في عملٍ توقّف.
    public DateTime? ExpiresAtUtc { get; private set; }

    private DistributedLease() { }

    public static DistributedLease ForWork(string name)
    {
        var trimmed = name?.Trim() ?? "";
        if (trimmed.Length is 0 or > NameMaxLength)
            throw new InvalidLeaseException($"اسمُ العمل المحروس مطلوب، حتى {NameMaxLength} حرفاً");
        if (!trimmed.All(c => char.IsAsciiLetterLower(c) || char.IsAsciiDigit(c) || c is '.' or '-' or ':'))
            throw new InvalidLeaseException("اسمُ العمل حروفٌ لاتينية صغيرة وأرقامٌ ونقاطٌ وشرطاتٌ ونقطتان");
        return new DistributedLease { Name = trimmed };
    }

    // حرٌّ في هذه اللحظة؟ تُقرأ في الاختبارات وفي التشخيص؛ الحجزُ نفسه يقع بتحديثٍ مشروط في
    // القاعدة، لا بقراءةٍ ثمّ كتابة — وذلك هو الفرق بين قفلٍ وسباق.
    public bool IsFreeAt(DateTime utcNow) => ExpiresAtUtc is null || ExpiresAtUtc <= utcNow;
}
