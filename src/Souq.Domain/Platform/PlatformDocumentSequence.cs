using Souq.Domain.Common;

namespace Souq.Domain.Platform;

// ============================================================================
// سلسلةُ ترقيم مستندات المنصّة ([ADR-0056](0056)): صفٌّ واحد لكل نوع مستند يحمل آخرَ رقمٍ صدر.
// جدولُ منصّةٍ **عالميّ بلا متجر** (الشكل C) — وهذا هو الفرق الجوهريّ عن `OrderNumberSequence`،
// وهو فرقٌ مقصود لا تقليد:
//
//   • أرقامُ الطلبات لكل متجر، لأنّ المُصدِر هو المتجر ولا يجوز أن يرى ترقيمُه حجمَ غيره.
//   • وأرقامُ فواتير المنصّة **سلسلةٌ واحدة لكل سوق**، لأنّ المُصدِر واحدٌ هو سوق: التسلسلُ غيرُ
//     المنقطع لكل مُصدِر مطلبٌ محاسبيٌّ في اختصاصاتٍ كثيرة، وتقسيمُه على التجّار يُنتج فجواتٍ
//     في سلسلةِ سوق نفسها.
//
// **ونوعان لا نوعٌ واحد:** للفاتورة سلسلتُها ولإشعار الدائن سلسلتُه. مستندان محاسبيّان مختلفان
// لا يتشاركان تسلسلاً، ودمجُهما يجعل «الفاتورة رقم 7» و«الإشعار رقم 7» اسمين لا يوجد أحدهما.
//
// **ولا إعادةَ ترقيمٍ بالسنة.** إعادةُ التصفير كلَّ سنةٍ شرطٌ في بعض الاختصاصات ولا شرطٌ في
// غيرها، ولا قاعدةَ اختصاصٍ يضعها المهندس (وهو درسُ ADR-0055 نفسه). فالسلسلةُ متّصلةٌ أبداً،
// ويومَ يطلب محاسبٌ تصفيراً سنويّاً يصير `Series` يحمل السنة ولا يتغيّر شيءٌ آخر — ولذلك هو نصٌّ
// لا تعداد.
// ============================================================================
public class PlatformDocumentSequence : Entity
{
    public const int SeriesMaxLength = 40;

    // أوّلُ رقمٍ يصدر. يبدأ من 1 لا من رقمٍ مُجمَّل: خلافاً لأرقام الطلبات، لا يضرّ أن يُعرف أنّ
    // هذه أوّلُ فاتورةٍ أصدرتها المنصّة — المشتري هنا شريكٌ تعاقديّ لا زائرُ متجر.
    public const int FirstNumber = 1;

    // أسماءُ السلاسل. ثابتان لا إعدادٌ: الكودُ نفسه هو من يطلب سلسلةَ مستندٍ بعينه.
    public const string InvoiceSeries = "platform-invoice";
    public const string CreditNoteSeries = "platform-credit-note";

    public string Series { get; private set; } = default!;
    public int LastNumber { get; private set; }

    private PlatformDocumentSequence() { }

    // أوّلُ صفٍّ لسلسلةٍ لم يصدر منها مستند. `LastNumber` يساوي أوّلَ رقم: مُصدِرُه يأخذه ثم
    // يزيده الصفُّ في المرّة التالية — النمطُ نفسه الذي يتبعه `OrderNumberSequence.Start()`.
    public static PlatformDocumentSequence Start(string series) =>
        new() { Series = series, LastNumber = FirstNumber };
}
