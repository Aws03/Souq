using Souq.Domain.Platform;

namespace Souq.Domain.ValueObjects;

// ============================================================================
// لقطةُ الضريبة كما طُبِّقت فعلاً — تُجمَّد على الطلب وعلى الفاتورة، **ولا تُحتسب مرّةً ثانية**
// ([ADR-0055](0055) §3).
//
// **ولهذا تحمل القيم لا مراجعها.** مرجعٌ إلى إصدارٍ كان كافياً لولا أنّ القراءةَ بعد سنةٍ تحتاج
// أن **تجد** ذلك الإصدار، وأن يكون هو بعينه. والقيمُ هنا تجعل ضريبةَ طلبٍ قابلةً لإعادة الاشتقاق
// من الطلب وحده: أيَّ إصدارٍ كان، وبأيّ عُرف، وأيَّ نسبةٍ بنقاطها، وكم كان مبلغها.
//
// ورقمُ الملفّ وإصداره محفوظان أيضاً — للتتبّع لا للقراءة: لو حُذف الملفّ من القاعدة (وهو ما لا
// يحدث) لبقيت اللقطة مكتفيةً بنفسها.
//
// **وحالةُ التحقّق تُلتقَط كما كانت لحظتَها.** فاتورةٌ صدرت بإصدارٍ تحقّق منه محاسبٌ تقول ذلك،
// وأخرى صدرت قبل تحقّقه تقول ذلك أيضاً — والفرقُ بينهما هو أوّلُ ما يُسأل عنه في مراجعة.
// ============================================================================
public sealed record TaxSnapshot(
    int TaxProfileId,
    int Version,
    string Jurisdiction,
    TaxPriceMode PriceMode,
    TaxVerificationState Verification,
    bool ShippingTaxable,
    IReadOnlyList<TaxSnapshotLine> Lines)
{
    // مجموعُ ما طُبِّق فعلاً: يُحتسب من الأسطر لا يُحفَظ بجانبها، فلا يفترقان أبداً.
    public decimal TotalAmount => Lines.Sum(l => l.Amount);

    public int TotalBasisPoints => Lines.Sum(l => l.BasisPoints);
}

// سطرُ نسبةٍ واحدة كما طُبِّقت: رمزُها واسمُها ونقاطُها والمبلغُ الذي أنتجته على هذا الطلب.
public sealed record TaxSnapshotLine(string Code, string Name, int BasisPoints, decimal Amount);
