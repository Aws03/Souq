namespace Souq.Application.Common.Security;

// ============================================================================
// ISessionValidator — هل ما زال توكن الوصول صالحاً لحسابه؟ التوكن يحمل ختم الأمان (sstamp) الذي
// يتغيّر مع كل ما يُبطل الجلسات (كلمة مرور، تعطيل، دور، سرقة رمز تجديد). التنفيذ في Infrastructure
// يخزّن الختم ثوانيَ معدودة كي لا يُسأل SQL مع كل طلب؛ Forget يُسقطه فوراً على هذه النسخة بعد التدوير.
// ============================================================================
public interface ISessionValidator
{
    Task<bool> IsCurrentAsync(int userId, string securityStamp, CancellationToken ct = default);

    void Forget(int userId);

    // ============================================================================
    // إسقاط أختام **كل** الحسابات على هذه النسخة (C3، TD-66).
    //
    // يُنادى حين تُبطَل جلسات متجر كاملةً بكتابةٍ مجمّعة: الأختام دُوِّرت في القاعدة بجملة واحدة،
    // فلا قائمة بمعرّفات من دُوِّر ختمه — و`Forget(userId)` تحتاج واحداً. والبديل تحميلُ معرّفات
    // كل حسابات المتجر، وهو بالضبط ما تتجنّبه الكتابة المجمّعة.
    //
    // وكلفة المسح كلّه مقبولة لأن سببه نادر (أرشفةُ متجر): قراءة ختمٍ واحدة لكل حساب نشط بعدها،
    // مرّةً واحدة. والبديل — 30 ثانية تُقبل فيها جلسةُ متجرٍ أُرشف — ليس مقبولاً: «الأرشفة تُبطل
    // الجلسات» إمّا أن تكون صحيحة أو لا تُقال.
    //
    // **حدٌّ مكتوب:** هذه النسخة وحدها. الإبطال بين النسخ عملُ C4.
    // ============================================================================
    // ============================================================================
    // إسقاطُ كلِّ الأختام المخزَّنة — **على هذه النسخة وعلى غيرها** (C4، [ADR-0057](0057)).
    //
    // ولهذا صار غيرَ متزامن: نشرُ الإشارة كتابةٌ في القاعدة. والمسارُ الوحيد الذي يستدعيه هو
    // إبطالُ جلسات متجرٍ بجملته (أرشفة، تعليق) — وهو بالضبط الموضعُ الذي يكون فيه بقاءُ جلسةٍ
    // مقبولةً على نسخةٍ أخرى ثلاثين ثانية فرقاً أمنياً لا فرقَ أداء.
    //
    // و`Forget(userId)` تبقى محلّيّةً ومتزامنة: إشارةٌ عالميّة لكلّ تغييرِ كلمةِ مرورٍ كانت
    // ستُسقط أختام كلّ الحسابات على كلّ النسخ لأجل حسابٍ واحد. فنافذتُها تبقى مدّةَ الانتهاء
    // (ثلاثون ثانية) على النسخ الأخرى، وهي مكتوبةٌ هنا كي تُعرَف لا لتُكتشَف.
    // ============================================================================
    Task ForgetAllAsync(CancellationToken ct = default);
}
