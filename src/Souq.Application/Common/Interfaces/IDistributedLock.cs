namespace Souq.Application.Common.Interfaces;

// ============================================================================
// قفلٌ يعبر نسخَ الخادم (C4، [ADR-0057](0057)): «هذا العمل تُجريه نسخةٌ واحدة في وقتٍ واحد».
//
// **ولماذا منفذ؟** لأنّ ما يحرسه قرارُ تطبيقٍ (أيُّ عملٍ لا يجوز أن يتوازى) وكيفَ يُحرَس قرارُ
// بنية تحتية (جدولٌ في SQL Server اليوم، وقد يصير غيرَه يوماً بلا أن يتغيّر مُنادٍ واحد).
//
// **والعقدُ محدودُ المدّة دائماً، ولا واجهةَ هنا لقفلٍ أبديّ.** نسخةٌ تسقط وهي حاملةٌ للقفل لا
// تُفرج عنه، فقفلٌ بلا انتهاءٍ يوقف عملاً إلى أن يتدخّل إنسان — وانتهاءُ المدّة هو آليةُ التعافي
// لا حالةُ خطأ. ولهذا **لا يوجد `AcquireAsync` ينتظر**: مَن لا يحصل على العقد لا يصطفّ، بل
// ينصرف ويحاول في الدورة التالية. عملٌ دوريّ لا يحتاج طابوراً — يحتاج ألّا يقع مرّتين.
// ============================================================================
public interface IDistributedLock
{
    // يحاول مرّةً واحدة بلا انتظار. `null` ⇒ نسخةٌ أخرى تحمله الآن، وهو جوابٌ عاديّ لا خطأ.
    Task<ILeaseHandle?> TryAcquireAsync(string work, TimeSpan duration, CancellationToken ct = default);
}

// ============================================================================
// عقدٌ مُمسَك. يُفرَج عنه بالتخلّص منه — وإن لم يُفرَج (سقطت العملية) انتهى بنفسه.
//
// **و`RenewAsync` تُعيد `false` حين يُفقَد العقد**، ولا ترمي: فقدانُه واقعةٌ متوقّعة — تأخّرت
// دورةٌ فانتهت المدّة وأخذته نسخةٌ أخرى — وعلى العامل أن **يتوقّف** عندها لا أن يمضي. وتجاهلُ
// جوابها هو بالضبط كيف يجري عملٌ في نسختين معاً وهو يظنّ أنه محروس.
// ============================================================================
public interface ILeaseHandle : IAsyncDisposable
{
    string Work { get; }

    Task<bool> RenewAsync(TimeSpan duration, CancellationToken ct = default);
}

// ============================================================================
// أسماءُ الأعمال المحروسة، مجموعةً كي تُقرأ معاً — ولأنّ اسمين متقاربين لعملٍ واحد يعنيان
// قفلين لا يحرس أيٌّ منهما شيئاً.
// ============================================================================
public static class GuardedWork
{
    // ============================================================================
    // **بادئةُ** كنسات المتاجر الدورية — لا اسمُ عملٍ بعينه. كلُّ كنسةٍ تُلحق اسمَها بها
    // (`sweeps.store.basket-cleanup`)، فتُمنع الكنسةُ الواحدة من الجريان في نسختين ولا تُمنع
    // كنسةٌ من الجريان بجانب أختها — فهما لا تتنازعان شيئاً.
    //
    // وما يُبرّر القفل أصلاً ليس فسادُ البيانات: العملياتُ كلُّها مضمونةُ التكرار. بل **فسادُ
    // الإشارة** — مصالحةُ عدّادات الحصص تُسجّل تحذيراً كلّما صحّحت انحرافاً، ونسختان تعُدّان
    // الصفوفَ نفسها معاً تُنتجان ذلك التحذير بلا انحرافٍ أصلاً.
    // ============================================================================
    public const string StoreSweeps = "sweeps.store";

    // ============================================================================
    // المطالبة الآلية (C6، ADR-0058). **بنطاق المنصّة لا بمتجر**، فاسمٌ واحد لها كلِّها — وهي
    // تقرأ ما استحقّ عبر المتاجر في استعلامٍ واحد، لا متجراً متجراً.
    //
    // وما يحرسه هذا العقد ليس فساد بيانات: التعليقُ محصَّنٌ بعلامةٍ على الفاتورة تمنع تكرارَه.
    // بل ضجيجٌ لا يُحصَّن — سطرا تدقيقٍ لتعليقٍ واحد، وإشعاران للتاجر نفسه.
    // ============================================================================
    public const string Dunning = "billing.dunning";

    // ويبقى **صندوقُ الصادر خارج هذه القائمة عمداً**، فلا اسمَ له هنا: لكلِّ رسالةٍ فيه عقدُ
    // إيجارها منذ المرحلة 14، فهو آمنٌ بنسختين بالبناء — وإخضاعُه لقفلٍ واحد كان سيحوّل مُرسِلَين
    // متوازيَين إلى مُرسِلٍ واحد، أي يُبطئ التسليم مقابل أمانٍ يملكه أصلاً.
}
