using Souq.Application.Common.Exceptions;
using Souq.Domain.Interfaces;

namespace Souq.Application.Features.Baskets;

// ============================================================================
// BasketWriter — إعادة المحاولة على تعارض التزامن في مسارات السلّة (F-28).
//
// **العطل.** أول قراءةٍ للسلّة بعد الدخول ليست قراءة: `BasketResolver.ResolveAsync` يضمّ سلّة
// الزائر إلى سلّة العميل ثم **يحذفها**. فطلبان يدخلان هذا المسار في اللحظة نفسها يتنازعان على
// الصفوف نفسها. قِيس على حزمة تعمل لا استُنتج: قراءتان متزامنتان لعميلٍ يحمل رمز سلّة زائر
// ⇒ **200 و409**؛ وضابطٌ بلا سلّة زائر ⇒ **200 و200**. أي أنّ كل مشترٍ ملأ سلّته ثم سجّل دخوله
// معرَّضٌ لتعارضٍ على **قراءة** — ورُصد فعلاً في سجلّ الحزمة:
// `Persistence conflict ConcurrencyConflictException on GET /api/basket`.
//
// ومن أين يأتي التزامن في المنتج؟ `/api/basket` و`/api/basket/quote` يدخلان المسار نفسه:
// `CartContext.reload` يُطلق الأولى عند تبدّل المستخدم (أي عند الدخول: لحظة الدمج بعينها)،
// وصفحة الدفع تُطلق الثانية من عدّة مسارات، فيتداخلان عليها. وتبويبان مفتوحان يكفيان وحدهما.
//
// **وهما سباقان لا واحد**، وهذا ما كشفه الاختبار بعد إصلاح الأوّل وحده (ستّ قراءات ⇒ أربع 409):
//
//   1. **حذف سلّة الزائر.** تفوز واحدة بالحذف، وتجد الأخرى `DELETE` بلا صفوف ⇒
//      `ConcurrencyConflictException`.
//   2. **إنشاء سلّة العميل.** عميلٌ بلا سلّة: كل طلبٍ متزامن يُنشئ له واحدة، والفهرس الفريد على
//      `(TenantId, CustomerId)` يقبل أوّلها ويرفض البقية ⇒ `UniqueConstraintViolationException`.
//
// كلاهما يظهر للمتسوّق 409 نفسه، وكلاهما يُعالَج بالإعادة: القراءة الجديدة تجد سلّة الزائر
// محذوفة فلا تدمج، وتجد سلّة العميل التي أنشأتها الفائزة فتستعملها بدل إنشاء ثانية. وهذا هو
// ما يفعله `OrderNumbers` أصلاً للسباق الثاني حين يُنشئ عدّاد المتجر أوّل مرّة.
//
// **لماذا الإعادة هي العلاج.** الخاسرة لم تُخطئ: الحالة التي طلبتها تحقّقت فعلاً — الفائزة دمجت
// وحذفت. فإعادةُ القراءة على الحالة الملتزمة تجد سلّة الزائر غائبة، فلا تدمج، وتُعيد السلّة
// المدموجة نفسها. وهذا هو الجواب الصحيح الذي كان الـ409 يحجبه.
//
// **ولماذا لا يُسقَط الحارس.** التعارض هنا يحرس صحّةً حقيقية: لولاه لدمجت الطلبتان سلّة الزائر
// مرّتين فتضاعفت أسطرها في سلّة العميل. الخسارة تُرجِع المعاملة كاملةً، فلا دمج مزدوج — نحن
// نُبقي الحارس ونُعيد المحاولة خلفه، كما يفعل المستودع للمخزون والكوبونات والمدفوعات والحسابات.
// ============================================================================
public sealed class BasketWriter
{
    // خمسٌ كـ`InventoryWriter` وأخواته، لا ستّ عشرة كـ`AccountWriter`: التنازع هنا ليس دفعةً من
    // طلباتٍ متماثلة على صفٍّ واحد، بل طلبا صفحةٍ واحدة تتسابقان على دمجٍ **يحدث مرّة واحدة** —
    // فأول إعادةٍ تجد الدمج قد تمّ ولا تجد ما تتنازع عليه. والحدّ هنا حارس دوران، لا ميزانية تصريف.
    public const int MaxAttempts = 5;

    private readonly IBasketRepository _baskets;

    public BasketWriter(IBasketRepository baskets) => _baskets = baskets;

    public async Task<T> SaveAsync<T>(Func<Task<T>> apply, CancellationToken ct)
    {
        for (var attempt = 1; ; attempt++)
        {
            ct.ThrowIfCancellationRequested();
            try { return await apply(); }
            catch (Exception e) when (e is ConcurrencyConflictException or UniqueConstraintViolationException
                                      && attempt < MaxAttempts) { _baskets.Reset(); }
            catch { _baskets.Reset(); throw; }
        }
    }
}
