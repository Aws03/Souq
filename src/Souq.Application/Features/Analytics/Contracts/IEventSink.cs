namespace Souq.Application.Features.Analytics.Contracts;

// ============================================================================
// مصرفُ الأحداث السلوكية — نفس عقد `ISearchLog` وبنفس السبب ([ADR-0050](0050) §1).
//
//   • **لا `Task`**: المُنادي لا ينتظر كتابةً. تسجيلُ ما فعله متسوّق ليس جزءاً من خدمته.
//   • **لا قيمة عائدة**: لا شيء يفعله المُنادي بالنتيجة، فإعادتُها تدعوه إلى انتظارها.
//   • **لا يرمي أبداً**: فشلُ القياس ليس فشلَ صفحة. متجرٌ يسقط لأن تحليلاته سقطت عطبٌ لا قياس.
//   • **ذاكرةٌ محدودة تُسقِط عند الامتلاء**، والمُسقَط يُعَدّ ويُسجَّل — فالفقد معروف لا مجهول.
//
// وضمانُه «مرّة على الأكثر»، وهو **أضعف** من ضمان صندوق الصادر عن قصد. ولهذا مكتوبٌ هنا صراحةً:
// **لا يُفوَّر من هذا المسار مالٌ ولا يُحتسب منه استهلاكٌ مُحاسَب.** قياسٌ مُعايَن أو مُسقَط لا
// يصلح أساساً لفاتورة، والحدث القابل للفوترة صفٌّ دائم بمفتاح تعطيلٍ حتميّ (ADR-0050 §1).
//
// **ولا يكتب شيئاً ما لم يُفعَّل الالتقاط.** قرار المالك C-08 = A أذن بمعرّف زائر مُعتِم، وأبقى
// ثلاثة أجوبة له: الأساس القانوني، ومدّة الحفظ، وهل تخرج الصفوف من الأردن. فالالتقاط **معطّل حتى
// تُضبَط**، وهو ما يعني «قبل أن يُكتب أوّل صفّ» حرفياً.
// ============================================================================
public interface IEventSink
{
    // name: من `BehaviouralEventNames`. payload: نوعٌ مسجَّل في `BehaviouralEventPayloads`.
    // ما لا يُعرَف اسمُه أو حمولتُه يُسقَط ويُعَدّ — لا يرمي.
    //
    // searchExecutionId: يُمرَّر **صكّاً** لا قراءةً — معالجُ البحث يصكّ المعرّف ويسجّل حدثه في
    // الطلب نفسه، فلا يستطيع قراءتَه من سياقٍ لم يحمله بعد. وما بعده من أحداث (نقرة، إضافة، شراء)
    // يقرؤه من السياق حين يردّه العميل، فلا يمرّره.
    void Record(string name, object payload, Guid? searchExecutionId = null);

    // هل الالتقاط مُفعَّل الآن؟ يُقرأ كي لا يبني المُنادي حمولةً لن تُكتب (لقطةُ قائمةٍ بستّين
    // عنصراً ليست مجانية). ليس شرطاً لصحّة `Record`: الإسقاط يقع فيه على أي حال.
    bool Enabled { get; }
}
