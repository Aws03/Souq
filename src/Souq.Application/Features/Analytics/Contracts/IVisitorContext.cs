namespace Souq.Application.Features.Analytics.Contracts;

// ============================================================================
// مَن يتصفّح الآن، بقدر ما يعرفه الخادم عنه — **بلا أيّ معلومةٍ تخصّ شخصاً بعينه**.
//
// يُنفَّذ في طبقة الـ API (من الطلب وملفّاته)، كما يُنفَّذ `IClientInfo` هناك ولنفس السبب: هذه
// قيمٌ يعرفها بروتوكول HTTP ولا يعرفها غيره. وحالاتُ الاستخدام تقرؤه ولا تبنيه.
//
// **ما ليس هنا مقصود:** لا IP، ولا وكيل مستخدم، ولا بصمةُ جهاز، ولا معرّفٌ مشتقٌّ من أيٍّ منها.
// `VisitorId` رقمٌ مُعتِم يصكّه الخادم ولا معنى له خارج سوق، و`CustomerId` **ليس هنا** أصلاً:
// ربطُ الزائر بالعميل يعيش في جدولٍ منفصل، لا في غلاف الحدث ([ADR-0050](0050) §5).
// ============================================================================
public interface IVisitorContext
{
    // null ⇒ لا معرّف زائر (إمّا لأنّ الالتقاط معطّل، أو لأنّ المعرّف نفسه معطّل — وهو جواب
    // C-08 = «لا» محفوظاً في الشكل نفسه). الأحداث تُكتب حينها بلا نسبة إلى زائر.
    string? VisitorId { get; }

    string? SessionId { get; }

    // معرّف تنفيذ البحث الذي جاءت منه هذه الصفحة، إن ردّه العميل. يُصكّ عند البحث ويُردّ مع النقرة
    // والإضافة والشراء — وبلا ردٍّ لا نسبة، والقُرب الزمنيّ ليس نسبةً.
    Guid? SearchExecutionId { get; }

    string? CorrelationId { get; }

    // السطح من مسار الطلب ونطاقه: متجر، لوحة تاجر، منصّة. يُقرأ لا يُخمَّن.
    string Surface { get; }
}
