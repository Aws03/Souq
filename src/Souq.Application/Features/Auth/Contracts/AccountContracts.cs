namespace Souq.Application.Features.Auth.Contracts;

// ============================================================================
// عقدا وحدة Identity مع وحدة Customers (TD-03/R-15، بُنيا في M9) — وبهما تنكسر الدورة الوحيدة التي
// يمنعها الرسم الهدف.
//
// **لماذا العقدان كلاهما مُعلَنان هنا، في Identity؟** لأن الاتجاه المُقرَّر (ModuleBoundaryAudit.md،
// "The cycle, exactly") هو **Customers → Identity**. فعقدٌ يُعلنه Customers ليستدعيه Identity كان
// سيوثّق الدورة لا يكسرها: يبقى سهمان. أمّا وإعلانهما هنا فكلّ إشارة تنطلق من Customers إلى Identity
// ولا شيء يعود — سهمٌ واحد، ولا دورة ممكنة في `AllowedContracts` أصلاً.
//
// وهذا **انعكاس تبعية** لا اختراعاً: `IVariantStockInitializer` يفعل الشيء نفسه (يُعلنه Catalog
// ويُنفّذه Inventory)، فالنمط موجود في المستودع قبل هذا.
//
// قبل M9 كانت الحال اثنتي عشرة عبوراً خامّاً — أربعٌ من Identity إلى Customers وثمانٍ بالعكس، ثمانٍ
// منها كتابة: كلّ وحدة تُحمِّل مستودع الأخرى وتُعدّل تجمّعها مباشرةً. العبور الآن نداءُ عقد.
// ============================================================================

// ── يُنفّذه Customers ────────────────────────────────────────────────────────
// ما تحتاجه Identity من ملفّات العملاء، ولا شيء غيره: "أُنشئ حساب" و"أيّ ملفٍّ يخصّ هذا الحساب".
// لا `Customer` ولا `ICustomerRepository` يعبران إلى Identity بعد هذا.
public interface IAccountProfiles
{
    // ملفّ العميل لحسابٍ أُنشئ للتوّ. **يُدرِج بلا حفظ** — الحفظ لمعاملة المستدعي، لأن التسجيل وحدة
    // واحدة: لا حساب بلا ملفّ شراء. يُستدعى بعد حفظ الحساب لأنه يحتاج معرّفه.
    Task CreateForAccountAsync(int userId, string fullName, string email, CancellationToken ct);

    // معرّف ملفّ العميل لهذا الحساب، أو null إن لم يكن له ملفّ (حساب منصّة، أو موظّف متجر).
    // يدخل في مطالبة `cid` داخل توكن الوصول وفي `/auth/me`.
    Task<int?> FindIdForAccountAsync(int userId, CancellationToken ct);
}

// ── يُنفّذه Identity ─────────────────────────────────────────────────────────
// ما تحتاجه Customers من الحساب. كانت تفعله بنفسها: تُحمِّل `IUserRepository`، وتنادي `User.Rename`
// و`User.Erase`، وتقرأ `PasswordHash` لتتحقّق منه، وتُلغي رموز التجديد صفّاً صفّاً — أي أنّ وحدةً
// أخرى كانت تُبطل جلسات Identity وتُعدّل تجمّعها. العقد يعيد ذلك إلى صاحبه.
public interface IAccountLifecycle
{
    // تحقّق من كلمة مرور الحساب. تُعيد false لحسابٍ غير موجود أيضاً، فلا يُميّز المتصل بين الحالتين.
    // كلمة المرور نفسها لا تخرج من Identity، ولا تجزئتها تدخل غيرها.
    Task<bool> VerifyPasswordAsync(int userId, string password, CancellationToken ct);

    // اسم الحساب يتبع اسم الملفّ (الرأس في `/auth/me` ورسائل الطلبات). **يُعدِّل بلا حفظ.**
    Task RenameAsync(int userId, string fullName, CancellationToken ct);

    // ============================================================================
    // محو الحساب: يُجرَّد من بياناته الشخصية، ويُوقَف، وتُلغى رموز تجديده، وتُنسى ذاكرة ختم جلسته
    // فتسقط توكنات الوصول القائمة فوراً.
    //
    // **يحفظ** — ومعه كلّ ما جهّزه المستدعي في وحدة العمل نفسها، فيبقى المحو كلّه ذرّةً واحدة كما كان
    // قبل العقد (الملفّ والسلة والمفضّلة والحساب في حفظٍ واحد). وهذا هو اصطلاح هذه الطبقة نفسه لا
    // استثناءً: `AuthSessionIssuer.IssueAsync` يحفظ ما جهّزه مستدعيه كذلك.
    //
    // والترتيب مقصود: النسيان **بعد** الحفظ. لو سبقه، أمكن لطلبٍ متزامن أن يعيد تخزين الختم القديم
    // (قرأه قبل الإيداع) فيبقى مقبولاً حتى ثلاثين ثانية.
    // ============================================================================
    Task EraseAsync(int userId, CancellationToken ct);
}
