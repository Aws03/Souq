using Souq.Application.Common.Exceptions;
using Souq.Domain.Interfaces;

namespace Souq.Application.Features.Auth;

// ============================================================================
// AccountWriter — إعادة المحاولة على تعارض التزامن في مسارات الحساب (F-25).
//
// **العطل.** كل دخولٍ ناجح يكتب في صفّ `User` دفتراً صغيراً (`RecordSuccessfulLogin`: تصفير عدّاد
// الإخفاق، رفع القفل، وقت آخر دخول)، و`User` يحمل rowversion. فدخولان لحسابٍ واحد في اللحظة نفسها
// يتسابقان على الصفّ، فيجد الثاني `WHERE RowVersion = @original` بلا صفوف. قِيس على الحزمة:
// ثمانية طلبات دخول متزامنة ⇒ 200 مرّتين و**409 ستّ مرّات**، وستة تغييرات كلمة مرور متزامنة
// ⇒ 200 مرّة و409 خمساً؛ والتسلسلي ينجح دائماً. أي أنّ من ينقر "دخول" نقرتين يرى تعارضاً.
//
// **لماذا الإعادة هي العلاج الصحيح، لا إسقاط الحارس.** الدفتر آخرُ كاتبٍ يفوز بطبيعته: الدخول
// المتزامن الذي التزم قبلنا كتب القيم نفسها. فالصواب أن نقرأ الحالة الملتزمة ونكتب فوقها، لا أن
// نُفشل تسجيل دخولٍ صحيح. و**الحارس يبقى كما هو**: لا rowversion يُزال، ولا مستوى عزل يتغيّر —
// نحن نعيد المحاولة على الحالة الجديدة، وهو ما يفعله المستودع أصلاً للمخزون والكوبونات والمدفوعات.
//
// **وما يُعاد ليس الحفظ وحده بل القرار كلّه.** المستدعي يُعيد قراءة الحساب ويُعيد التحقّق من كلمة
// المرور والقفل والحالة في كل محاولة. هذا شرط أمني لا تحسين: لو أعدنا الحفظ وحده لأصدرنا جلسةً
// بناءً على تجزئة كلمة مرور قد تكون تغيّرت للتوّ في الطلب المتزامن الذي فاز. بالإعادة الكاملة،
// تغييرُ كلمة المرور أثناء السباق يُنتج رفضاً صحيحاً لا جلسةً مسروقة.
// ============================================================================
public sealed class AccountWriter
{
    // ========================================================================
    // العدد ليس ذوقاً: **كل جولة تُدخل كاتباً واحداً**. الطلبات المتزامنة كلها تقرأ النسخة
    // نفسها، فيفوز أحدها ويخسر الباقي، ثم يُعيدون فيفوز واحد ويخسر الباقي. فتصريفُ دفعةٍ
    // من N طلباً يحتاج N جولة تقريباً — لا أقلّ. وقِيس ذلك لا استُنتج: بخمس محاولات بقي من
    // ثماني دخولات متزامنة **409 مرّتين** (بعد أن كانت ستّاً بلا إعادة أصلاً).
    //
    // فلماذا ستّة عشر؟ لأنّها تتجاوز أي دفعةٍ متزامنة لحسابٍ **واحد** يُنتجها بشر: تبويبات،
    // أجهزة، نقرةٌ مكرّرة، عميلٌ يُعيد الإرسال. وما تجاوزها ليس مستخدماً، و409 عنده صادق.
    //
    // وهذا السقف مسموحٌ به **فقط** لأن المحاولة رخيصة: `PasswordCheck` يمنع إعادة حساب
    // BCrypt، فتبقى المحاولة قراءةً بمفتاح وكتابةَ صفّ. بدونه كان كل توسيعٍ هنا توسيعاً
    // لمضخّة إنهاك — ولهذا لا يُرفع هذا العدد أبداً بمعزل عن ذلك الضمان.
    //
    // (`InventoryWriter` وأخواته تقف عند خمس: تنازعها على صفّ مشترك بين مستخدمين مختلفين،
    // والخسارة هناك رفضُ عمليةٍ لها بديل، لا رفضُ دخولٍ صحيح.)
    // ========================================================================
    public const int MaxAttempts = 16;

    private readonly IUserRepository _users;

    public AccountWriter(IUserRepository users) => _users = users;

    public async Task<T> SaveAsync<T>(Func<Task<T>> apply, CancellationToken ct)
    {
        for (var attempt = 1; ; attempt++)
        {
            ct.ThrowIfCancellationRequested();
            try
            {
                return await apply();
            }
            catch (ConcurrencyConflictException) when (attempt < MaxAttempts)
            {
                // المحاولة التالية تقرأ الملتزم: `Reset` ينسى الحساب ورمزه وإشعاره دون سجلّ التدقيق.
                _users.Reset();
            }
            catch
            {
                _users.Reset();
                throw;
            }
        }
    }
}
