using Souq.Application.Common.Interfaces;

namespace Souq.Application.Features.Auth;

// ============================================================================
// تحقّقٌ من كلمة المرور يُحسب مرّة لكل تجزئة، لا مرّة لكل محاولة.
//
// BCrypt بطيء عمداً — عشرات إلى مئات المللي ثانية — وهذا بالضبط ما يحميه من القوة الغاشمة.
// لكن إعادة المحاولة عند تعارض التزامن (`AccountWriter`) تعيد القرار كلّه، فتعيد معه التجزئة:
// محاولاتٌ عدّة ⇒ أضعافُ الزمن والمعالج لطلب دخولٍ واحد. وذلك ليس بطئاً فحسب، بل **مضخّة
// إنهاك**: من يريد إشغال الخادم يُطلق طلبات دخول متزامنة على حسابٍ واحد فيتسابق الدفتر،
// فتُعاد المحاولات، فتُعاد التجزئة — بلا أن يعرف كلمة المرور أصلاً. فالمحاولة يجب أن تكون
// رخيصة كي يُسمح بعددٍ منها يكفي لتصريف الازدحام.
//
// ولا تُحفظ النتيجة مجرّدة بل مقرونةً بالتجزئة التي حُسبت عليها: إن تغيّرت بين محاولتين —
// أي أنّ تغييرَ كلمة مرور متزامناً فاز بالسباق — بطلت النتيجة وأُعيد حسابها على الجديدة.
// فالتوفير في الحالة الشائعة (ازدحامٌ على دفتر الدخول لا يمسّ التجزئة)، والصحّة مصونة في
// الحالة التي تهمّ: لا تُصدَر جلسة بناءً على تجزئةٍ لم تعد هي المحفوظة.
//
// العمر: طلبٌ واحد. لا يُشارَك بين طلبين ولا يُسجَّل في الحاوية — يُنشأ في المعالج ويموت معه،
// فكلمة المرور الخام لا تعيش أطول من الطلب الذي جاء بها.
// ============================================================================
public sealed class PasswordCheck
{
    private readonly IPasswordHasher _hasher;
    private readonly string _password;
    private string? _checked;
    private bool _matched;

    public PasswordCheck(IPasswordHasher hasher, string password)
    {
        _hasher = hasher; _password = password;
    }

    public bool Matches(string passwordHash)
    {
        if (_checked == passwordHash) return _matched;

        _matched = _hasher.Verify(_password, passwordHash);
        _checked = passwordHash;
        return _matched;
    }
}
