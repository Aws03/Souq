namespace Souq.Application.Features.Products;

// ============================================================================
// سياسة حفظ سجلّ البحث (M13) — موجودة **من أول سطر**، لا مؤجّلة.
//
// TD-16 يسجّل أنّ لا سياسةَ حفظٍ لأي جدول في هذا النظام، وأنّ الجداول التي فيها بيانات شخصية تنتظر جواباً
// قانونياً عن مدّة الحفظ. سجلّ البحث لا بيانات شخصية فيه بالبناء (`SearchQueryLog`)، فمدّته قرارٌ هندسي
// لا قانوني — وهذا الملفّ هو القرار: الجدول الأكثر كتابةً في النظام لا يُسلَّم بلا حدّ لنموّه.
//
// **تسعون يوماً** لأنّ السؤال الذي يخدمه السجلّ موسميّ قصير ("ما يُبحث عنه هذا الربع ولا يوجد")، وربعٌ
// كاملٌ يكفيه. وأطول من ذلك يُخزَّن ليُقرأ مرّةً واحدة في مقارنةٍ سنوية لا تطلبها أي شاشة.
//
// **والمسح كل ست ساعات لا كل دقيقة**: صفوفُ يومٍ زائدة لا تؤذي، وحذفٌ متواتر على جدولٍ يُكتب فيه باستمرار
// يزاحم الكتابة على نفس الصفحات. صفرٌ يعطّل المسح — للاختبارات التي ترسل الأمر بنفسها.
// ============================================================================
public sealed class SearchLogSettings
{
    public int RetentionDays { get; set; } = 90;
    public int PurgeIntervalMinutes { get; set; } = 360;

    // حدّ الدفعة: حذفٌ واحد لا يُقفل الجدول طويلاً. المسح يعيد المحاولة في الدورة التالية إن بقي شيء.
    public int PurgeBatchSize { get; set; } = 5000;

    // ============================================================================
    // نافذة تجميع الكتابة: الكاتب ينتظر أول سطر ثم يجمع ما يصل خلالها في حفظٍ واحد.
    //
    // ثانيتان افتراضاً — قياسٌ لا يحتاج فوريّة، ومئات الـ INSERT المنفردة تصير حفظاً واحداً. وهي مُعدَّة لا
    // ثابتة لسببين: الاختبارات تُقصّرها كي تفحص مسار الكتابة الحقيقي بلا انتظارٍ في كل اختبار، ونشرٌ تحت حملٍ
    // عالٍ قد يُطيلها ليُكبر الدفعة. والحدّ الأدنى عشر مللي ثانية: أقصر من ذلك يعني دورةً بلا تجميع.
    // ============================================================================
    public int WriteBatchMilliseconds { get; set; } = 2000;

    public TimeSpan WriteBatchWindow => TimeSpan.FromMilliseconds(WriteBatchMilliseconds);
}
