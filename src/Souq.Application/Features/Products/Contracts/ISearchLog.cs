namespace Souq.Application.Features.Products.Contracts;

// ============================================================================
// تسجيل بحثٍ جرى (M13). العقد **متعمَّد التفاهة**: لا `Task`، ولا قيمة راجعة، ولا استثناء.
//
// لأنّ هذا هو الشرط الذي تفرضه المرحلة: "لا يُحتجز طلبٌ على كتابة سجلّ". دالّةٌ تعيد `Task` تدعو
// مستدعيها إلى `await`، و`await` في مسار البحث يعني أنّ إبطاء الجدول أو امتلاء القرص يُبطئ بحث
// المتسوّق — وهو أسوأ ما يمكن أن يفعله قياسٌ بما يقيسه. فالتنفيذ يُودع في ذاكرةٍ محدودة ويعود فوراً،
// وكاتبٌ في الخلفية يُفرغها على دفعات.
//
// ومحدودة تعني أنّها **تُسقط** عند الامتلاء لا تنمو ولا تنتظر: سجلّ البحث إحصاء، وفقدُ بعضه تحت ضغطٍ
// شديد مقبول؛ أمّا أن يُعلَّق بحثٌ أو يُستهلك ما لا حدّ له من الذاكرة فليس مقبولاً. والإسقاط يُعَدّ
// ويُسجَّل، فلا يكون صامتاً.
// ============================================================================
public interface ISearchLog
{
    /// يُودع البحث ويعود فوراً. لا يرمي أبداً — فشل التسجيل ليس فشل بحث.
    void Record(string? term, int resultCount, string culture);
}

// ============================================================================
// تنفيذ سياسة الحفظ (M13). منفذٌ منفصل عن `ISearchLog` عن قصد: ذاك يُنادى ملايين المرّات ولا يرمي، وهذا
// يُنادى كل ساعات ويرمي إن فشل (المنسّق يسجّل ويعيد في الدورة التالية). دمجُهما كان سيجعل عقداً واحداً
// يحمل ضمانين متناقضين.
//
// يعمل على متجر السياق وحده — مرشّح المستأجر في `AppDbContext` يضمن ذلك، فلا يحذف المسحُ سجلّ متجرٍ آخر.
// ============================================================================
public interface ISearchLogRetention
{
    /// يحذف حتى `max` صفٍّ أقدم من `before`. يعيد ما حُذف فعلاً.
    Task<int> PurgeBeforeAsync(DateTime before, int max, CancellationToken ct);
}
