// كانت الروابط بالمعرّف التسلسلي وحده (/products/42): لا يقول شيئاً لقارئ ولا لمحرّك بحث،
// ويكشف كم منتجاً في المتجر. المتجر يملك أصلاً slug لكل منتج (ProductDto.Slug) ونقطة
// /products/by-slug — كانت في عميل الـ API بلا مستعمل.
//
// الرابط بالاسم هو القانوني، والمعرّف يبقى يعمل: روابط قديمة ومشاركات سابقة لا تُكسر،
// بل تُحوَّل إلى الشكل القانوني بعد وصول المنتج.
// ============================================================================
export const productPath = (product) => `/products/${product?.slug || product?.id}`;

// معرّف تسلسلي أم slug؟ الرقم وحده معرّف — وslug صالح لا يكون أرقاماً فقط (يُشتقّ من الاسم).
export const isProductId = (handle) => /^[1-9]\d*$/.test(String(handle ?? ''));

// هل الرابط الحالي هو القانوني لهذا المنتج؟ لا ⇒ يُستبدَل (replace) فلا يمتلئ سجلّ الرجوع.
export const needsCanonicalRedirect = (handle, product) =>
  Boolean(product?.slug) && String(handle) !== product.slug;
