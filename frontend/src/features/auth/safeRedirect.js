export const HOME = '/';

// المتصفّح يُسقط المسافات وأحرف تحكّم C0 من أول العنوان قبل قراءته. كلّها رموزها أصغر من المسافة أو تساويها،
// فالمقارنة بالمسافة تصفها كاملةً — وبلا أي رمز هروب: حرف تحكّم غير مرئي داخل فحص أمني يضيع في أول نسخ أو
// تنسيق ولا يبدو ناقصاً لمن يراجع.
const isIgnorableLeading = (character) => character <= ' ';

function withoutLeadingIgnorable(value) {
  let start = 0;
  while (start < value.length && isIgnorableLeading(value[start])) start += 1;
  return value.slice(start);
}

export function safeRedirect(from, fallback = HOME) {
  if (typeof from !== 'string') return fallback;

  // التنظيف قبل الحكم لا بعده — وإلّا مرّ مسار مسبوق بحرف تحكّم من الفحص ثم صار خارجياً عند التنقّل.
  const path = withoutLeadingIgnorable(from);

  if (!path.startsWith('/')) return fallback;               // نسبي، أو مطلق بمخطّط (https://…)
  if (path[1] === '/' || path[1] === '\\') return fallback; // //host و /\host كلاهما خارجي
  if (path === '/login') return fallback;                   // لا نعيد المستخدم إلى الشاشة التي غادرها للتوّ

  return path;
}
